"""Writes src/geothai/_data/ from the GeoThai/data release named in data.version."""

import json
import urllib.request
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "geothai" / "_data"
VERSION = (ROOT / "data.version").read_text(encoding="utf-8").strip()


def get_json(path: str) -> Any:
    url = f"https://raw.githubusercontent.com/GeoThai/data/{VERSION}/{path}"
    with urllib.request.urlopen(url, timeout=60) as res:
        return json.load(res)


def get(path: str) -> list[dict[str, Any]]:
    return get_json(path)


def write(name: str, rows: list[list[str]]) -> None:
    text = json.dumps(rows, ensure_ascii=False, separators=(",", ":"))
    (OUT / f"{name}.json").write_text(text + "\n", encoding="utf-8")


PY_TYPES = {"string": "str", "array": "tuple[str, ...]", "date": "str"}


def dataclass_source(package: dict[str, Any], resource: str, name: str, doc: str) -> str:
    """One frozen dataclass from the field list and descriptions in datapackage.json."""
    fields = next(r for r in package["resources"] if r["name"] == f"{resource}-json")["schema"]
    lines = ["@dataclass(frozen=True, slots=True)", f"class {name}:", f'    """{doc}"""', ""]
    for f in fields["fields"]:
        constraints: dict[str, Any] = f.get("constraints") or {}
        enum: list[str] | None = constraints.get("enum")
        base = f"Literal[{', '.join(repr(v) for v in enum)}]" if enum else PY_TYPES.get(f["type"])
        if base is None:
            raise ValueError(f"{resource}.{f['name']}: no Python type for {f['type']!r}")
        py = base if constraints.get("required") else f"{base} | None"
        lines += [f"    {f['name']}: {py}", f'    """{f["description"]}"""', ""]
    return "\n".join(lines).rstrip() + "\n"


def codes_source(name: str, rows: list[dict[str, Any]]) -> str:
    body = ",\n".join(f'    "{r["code"]}"' for r in rows)
    return f"{name} = Literal[\n{body},\n]\n"


def names(rows: list[dict[str, Any]]) -> list[list[str]]:
    return [[r["code"], r["name_th"], r["name_en"]] for r in rows]


provinces = get("json/provinces.json")
districts = get("json/districts.json")
# The package reads each parent from the start of a code, so check that the data agrees.
for d in districts:
    if not d["code"].startswith(d["province_code"]):
        raise ValueError(f"district {d['code']} is not under {d['province_code']}")

subdistricts = get("json/subdistricts.json")
for s in subdistricts:
    if not s["code"].startswith(s["district_code"]):
        raise ValueError(f"subdistrict {s['code']} is not under {s['district_code']}")

write("provinces", names(provinces))
write("districts", names(districts))
write(
    "subdistricts",
    [[s["code"], s["name_th"], s["name_en"], " ".join(s["postal_codes"])] for s in subdistricts],
)
package = get_json("datapackage.json")
(ROOT / "src" / "geothai" / "_schema.py").write_text(
    "\n\n".join(
        [
            f'"""Generated by scripts/data.py from GeoThai/data {VERSION}. Do not edit."""\n\n'
            "from dataclasses import dataclass\nfrom typing import Literal\n",
            dataclass_source(package, "provinces", "Province", "A province of Thailand."),
            dataclass_source(
                package, "districts", "District", "A district (amphoe or khet) of Thailand."
            ),
            dataclass_source(
                package,
                "subdistricts",
                "Subdistrict",
                "A subdistrict (tambon or khwaeng) of Thailand.",
            ),
            codes_source("ProvinceCode", provinces),
            codes_source("DistrictCode", districts),
            codes_source("SubdistrictCode", subdistricts),
        ]
    ),
    encoding="utf-8",
)
print(
    f"GeoThai/data {VERSION}: {len(provinces)} provinces, {len(districts)} districts,"
    f" {len(subdistricts)} subdistricts"
)
